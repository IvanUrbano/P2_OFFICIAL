/* ─── Constants ──────────────────────────────────────────────────────── */

const monthLabel = month => new Date(2000, Number(month) - 1, 1)
  .toLocaleDateString('en-US', { month: 'long' });
const quarterLabel = quarter => {
  const start = (Number(quarter) - 1) * 3 + 1;
  return `Q${quarter} — ${monthLabel(start)}–${monthLabel(start + 2)}`;
};

const REPORT_TYPES = [
  { key: 'monthly', title: 'Monthly', desc: 'City-wide or per barangay' },
  { key: 'quarterly', title: 'Quarterly', desc: 'Quarter summary and trends' },
  { key: 'annual', title: 'Annual', desc: 'Full-year case analysis' },
  { key: 'barangay', title: 'Barangay', desc: 'Per-barangay detail view' },
];

/* ─── Report Builder ─────────────────────────────────────────────────── */

const fmtDate = value => value
  ? new Date(value).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' })
  : null;
const pct = value => (value != null ? `${value}%` : 'N/A');

/**
 * Turns the API payload into ONE ordered list of blocks. The on-screen preview, the PDF and the
 * Excel workbook all read these same blocks, so they cannot disagree about what a report says.
 * Block kinds: 'text' / 'list' (items), 'kv' (rows of [label, value]),
 * 'table' (headers + rows; textColumns are left-aligned, the rest right-aligned).
 */
function buildReport(data, config) {
  const { summary = {}, outcomes, demographics, trend, barangayDistribution, riskSummary, recommendations,
    cases, caseProfile, forecast, facilityPerformance, barangayProfile, outcomeReconciliation,
    riskAssessmentPeriod, incidenceLabel, comparison, alerts, interventions, older } = data;
  const meta = data.report || {};
  const { type, barangay, month, quarter, year, allBarangays: barangays } = config;
  const isCitywide = !barangay;
  const scopeText = isCitywide ? 'across Pasig City' : `in Barangay ${barangay}`;

  let title, headerTitle, subtitle, footerPeriod, periodText;
  if (type === 'monthly') {
    periodText = `${monthLabel(month)} ${year}`;
    title = `Monthly TB Report — ${periodText}${barangay ? ' · ' + barangay : ' · City-wide'}`;
    headerTitle = 'TUBERCULOSIS MONTHLY REPORT';
    subtitle = `${periodText}  ·  ${isCitywide ? 'City-wide' : barangay}`;
    footerPeriod = `Report Period: ${periodText}`;
  } else if (type === 'quarterly') {
    periodText = `${quarterLabel(quarter)} ${year}`;
    title = `Quarterly TB Report — ${periodText}`;
    headerTitle = 'TUBERCULOSIS QUARTERLY REPORT';
    subtitle = periodText;
    footerPeriod = `Report Period: ${periodText}`;
  } else if (type === 'annual') {
    periodText = `Calendar Year ${year}`;
    title = `Annual TB Report — ${year}`;
    headerTitle = 'TUBERCULOSIS ANNUAL REPORT';
    subtitle = periodText;
    footerPeriod = `Annual Report: ${year}`;
  } else {
    periodText = `Calendar Year ${year}`;
    title = `Barangay TB Report — ${barangay} · ${year}`;
    headerTitle = 'BARANGAY TB DETAIL REPORT';
    subtitle = `Barangay ${barangay}  ·  ${year}`;
    footerPeriod = `Barangay ${barangay} · ${year}`;
  }

  const total = summary.totalCases ?? 0;
  const blocks = [];
  // Plain-language interpretation under a table, written by the same functions as the dashboard
  // charts so a report can never say something different from the screen. Skipped when there is
  // nothing to say; the comparison sentence is skipped when the earlier year has no records.
  const interpret = (id, text) => { if (text) blocks.push({ id: `${id}Insight`, title: 'Interpretation', kind: 'text', items: [text] }); };
  const olderLabel = older?.label;

  // Report details
  const details = [
    ['Report Period', periodText],
    ['Coverage', isCitywide ? 'Pasig City (city-wide)' : `Barangay ${barangay}`],
    ['Generated On', meta.generatedAt ? new Date(meta.generatedAt).toLocaleString('en-US', { month: 'long', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit' }) : '—'],
  ];
  if (meta.generatedBy) {
    const gb = meta.generatedBy;
    const who = gb.fullName && gb.fullName !== gb.username ? `${gb.fullName} (${gb.username})` : gb.username;
    details.push(['Generated By', gb.role ? `${who} · ${gb.role}` : who]);
  }
  if (meta.reportRef) details.push(['Report Reference', meta.reportRef]);
  if (meta.lastSync) details.push(['Records Last Updated', fmtDate(meta.lastSync)]);
  blocks.push({ id: 'details', title: 'Report Details', kind: 'kv', rows: details });

  // Executive summary
  const executive = [
    `${total} TB case${total === 1 ? ' was' : 's were'} recorded in ${type === 'annual' || type === 'barangay' ? year : periodText} ${scopeText}.`,
  ];
  if (comparison && comparison.previousCases > 0) {
    const diff = total - comparison.previousCases;
    executive.push(`This is ${diff === 0 ? 'unchanged from' : `${Math.abs(diff)} case${Math.abs(diff) === 1 ? '' : 's'} ${diff > 0 ? 'more than' : 'fewer than'}`} ${comparison.previousLabel} (${comparison.previousCases}).`);
  }
  if (summary.onTreatmentCases > 0) {
    executive.push(`${summary.onTreatmentCases} case${summary.onTreatmentCases === 1 ? ' is' : 's are'} recorded as on treatment.`);
  }
  if (summary.successRate != null) {
    executive.push(`The treatment success rate is ${summary.successRate}% for the ${summary.cohortYear ?? 'previous-year'} treatment cohort, ${summary.successRate >= 85 ? 'at or above' : 'below'} the 85% target.`);
  }
  if (summary.fatalityRate != null) executive.push(`The case fatality rate is ${summary.fatalityRate}% among evaluated outcomes.`);
  if (barangayProfile) {
    executive.push(`${barangay} is classified ${barangayProfile.riskLevel} risk${barangayProfile.trendDirection ? ` with a ${String(barangayProfile.trendDirection).toLowerCase()} long-term trend` : ''} in the latest assessment.`);
  } else if (riskSummary?.length) {
    const high = riskSummary.filter(r => r.riskLevel === 'High' || r.riskLevel === 'Very High').length;
    executive.push(`${high} of ${riskSummary.length} barangays with cases are classified High risk in the latest assessment.`);
  }
  blocks.push({ id: 'executive', title: 'Executive Summary', kind: 'text', items: executive });

  // Summary figures
  const kpiRows = [
    ['Total Cases', total],
    ['Diagnosed', summary.diagnosedCases ?? 0],
    ['On Treatment', summary.onTreatmentCases ?? 0],
    [`Treatment Success Rate${summary.cohortYear ? ` (${summary.cohortYear} cohort${summary.evaluatedCount ? `, ${summary.evaluatedCount} patients` : ''})` : ''}`, pct(summary.successRate)],
    [`Case Fatality Rate${summary.fatalityEvaluated ? ` (${summary.fatalityDied ?? 0} of ${summary.fatalityEvaluated} evaluated)` : ''}`, pct(summary.fatalityRate)],
  ];
  if (barangayProfile) {
    kpiRows.push(['Risk Classification', barangayProfile.riskLevel]);
    if (barangayProfile.trendDirection) kpiRows.push(['Long-term Trend', barangayProfile.trendDirection]);
    kpiRows.push(['Population', barangayProfile.population != null ? barangayProfile.population.toLocaleString() : 'N/A']);
    kpiRows.push([barangayProfile.incidenceLabel || 'Incidence / 100k', barangayProfile.incidence != null ? barangayProfile.incidence : 'N/A']);
  }
  blocks.push({ id: 'summary', title: 'Summary', kind: 'kv', rows: kpiRows });

  // Comparison with earlier periods
  if (comparison) {
    const change = prev => {
      if (!prev) return total ? 'New (none before)' : '0%';
      const diff = ((total - prev) / prev) * 100;
      return `${diff > 0 ? '+' : ''}${diff.toFixed(1)}%`;
    };
    const cmpRows = [[`${periodText} (this report)`, total, '—'],
      [comparison.previousLabel, comparison.previousCases, change(comparison.previousCases)]];
    if (!comparison.sameAsPrevious) cmpRows.push([comparison.yearAgoLabel, comparison.yearAgoCases, change(comparison.yearAgoCases)]);
    blocks.push({
      id: 'comparison', title: 'Comparison with Previous Periods', kind: 'table',
      headers: ['Period', 'Cases', 'Change vs. Previous'], rows: cmpRows,
    });
  }

  if (older) {
    const rate = v => (v != null ? `${v}%` : 'N/A');
    const delta = (now, then, unit = '') => (now == null || then == null ? 'N/A' : `${now - then > 0 ? '+' : ''}${Number((now - then).toFixed(1))}${unit}`);
    blocks.push({
      id: 'kpiCompare', title: `Key Figures Compared with ${olderLabel}`, kind: 'table',
      headers: ['Measure', 'This Report', olderLabel, 'Change'],
      rows: [
        ['Total cases', total, older.totalCases, delta(total, older.totalCases)],
        ['Treatment success rate', rate(summary.successRate), rate(older.successRate), delta(summary.successRate, older.successRate, ' pts')],
        ['Case fatality rate', rate(summary.fatalityRate), rate(older.fatalityRate), delta(summary.fatalityRate, older.fatalityRate, ' pts')],
      ],
    });
  }
  if (comparison && comparison.previousCases > 0) {
    interpret('comparison', `${periodText} had ${total} case${total === 1 ? '' : 's'}, compared with ${comparison.previousCases} in ${comparison.previousLabel}${comparison.sameAsPrevious ? '' : ` and ${comparison.yearAgoCases} in ${comparison.yearAgoLabel}`}.`);
  }

  // Counts over the case list the report is built on
  const tally = (list, keyFn) => {
    const map = {};
    list?.forEach(c => { const k = keyFn(c) || 'Unknown'; map[k] = (map[k] || 0) + 1; });
    return Object.entries(map).sort((a, b) => b[1] - a[1]);
  };
  const countRows = entries => entries.map(([label, count]) => [label, count, `${cases?.length ? Number(((count / cases.length) * 100).toFixed(1)) : 0}%`]);

  blocks.push({
    id: 'outcomes', title: 'Treatment Outcome Breakdown', kind: 'table',
    headers: ['Outcome', 'Count', 'Percentage'],
    rows: outcomes?.map(o => [o.outcome_status, o.count, `${o.percentage}%`]) || [],
    emptyText: 'No treatment outcomes are recorded for this period.',
  });
  interpret('outcomes', outcomeInsight((outcomes || []).map(o => ({ name: o.outcome_status, Cases: o.count })), {
    previous: older ? { label: olderLabel, items: older.outcomes.map(o => ({ name: o.outcome_status, Cases: o.count })) } : null,
  }));
  blocks.push({
    id: 'sex', title: 'Sex Distribution', kind: 'table', headers: ['Sex', 'Count', 'Percentage'],
    rows: demographics?.sex?.map(s => [s.sex, s.count, `${s.percentage}%`]) || [],
  });
  interpret('sex', shareInsight((demographics?.sex || []).map(s => ({ name: s.sex, value: s.count })), {
    noun: 'sex', previous: older ? { label: olderLabel, items: older.sex.map(s => ({ name: s.sex, value: s.count })) } : null,
  }));
  blocks.push({
    id: 'age', title: 'Age Distribution', kind: 'table', headers: ['Age Group', 'Count', 'Percentage'],
    rows: demographics?.ageGroups?.map(r => [r.age_group, r.count, `${r.percentage}%`]) || [],
  });
  interpret('age', shareInsight((demographics?.ageGroups || []).map(r => ({ name: r.age_group, value: r.count })), {
    noun: 'age group', previous: older ? { label: olderLabel, items: older.ageGroups.map(r => ({ name: r.age_group, value: r.count })) } : null,
  }));

  if (caseProfile) {
    blocks.push({
      id: 'profile', title: 'Case Profile', kind: 'kv',
      rows: [
        ['New Cases', caseProfile.newCases],
        ['Relapse / Recapture', caseProfile.relapse],
        ['Pulmonary', caseProfile.pulmonary],
        ['Extra-pulmonary', caseProfile.extraPulmonary],
      ],
    });
  }

  // Bacteriological status, counted from the same case list the report is built on
  const bactMap = {};
  cases?.forEach(c => { const s = c.bacteriological_status || 'Unknown'; bactMap[s] = (bactMap[s] || 0) + 1; });
  const bactRows = Object.entries(bactMap).sort((a, b) => b[1] - a[1])
    .map(([status, count]) => [status, count, `${cases.length ? Number(((count / cases.length) * 100).toFixed(1)) : 0}%`]);
  blocks.push({ id: 'bact', title: 'Bacteriological Status', kind: 'table', headers: ['Status', 'Count', 'Percentage'], rows: bactRows });

  if (cases?.length) {
    blocks.push({ id: 'status', title: 'Case Status', kind: 'table', headers: ['Status', 'Count', 'Percentage'], rows: countRows(tally(cases, c => c.case_status)) });
    blocks.push({ id: 'regGroup', title: 'Registration Group', kind: 'table', headers: ['Registration Group', 'Count', 'Percentage'], rows: countRows(tally(cases, c => c.registration_group)) });
    blocks.push({ id: 'site', title: 'Anatomical Site', kind: 'table', headers: ['Anatomical Site', 'Count', 'Percentage'], rows: countRows(tally(cases, c => c.anatomical_site)) });

    // Sex by age group
    const AGE_ORDER = ['0-14', '15-24', '25-34', '35-44', '45-54', '55-64', '65+', 'Unknown'];
    const ageOf = a => (a == null ? 'Unknown' : a <= 14 ? '0-14' : a <= 24 ? '15-24' : a <= 34 ? '25-34' : a <= 44 ? '35-44' : a <= 54 ? '45-54' : a <= 64 ? '55-64' : '65+');
    const sexKey = c => { const s = String(c.sex || '').trim().toUpperCase(); return s.startsWith('M') ? 'Male' : s.startsWith('F') ? 'Female' : 'Unknown'; };
    const grid = {};
    cases.forEach(c => { const ag = ageOf(c.age); grid[ag] = grid[ag] || { Male: 0, Female: 0, Unknown: 0 }; grid[ag][sexKey(c)] += 1; });
    const gridRows = AGE_ORDER.filter(ag => grid[ag]).map(ag => [ag, grid[ag].Male, grid[ag].Female, grid[ag].Unknown, grid[ag].Male + grid[ag].Female + grid[ag].Unknown]);
    blocks.push({ id: 'sexAge', title: 'Cases by Age Group and Sex', kind: 'table', headers: ['Age Group', 'Male', 'Female', 'Unknown', 'Total'], rows: gridRows });

    // Weekly pattern within a single month
    const isSingleMonth = type === 'monthly';
    if (isSingleMonth) {
      const weeks = {};
      cases.forEach(c => {
        if (!c.date_of_diagnosis) return;
        const day = Number(String(c.date_of_diagnosis).slice(8, 10));
        if (!day) return;
        const w = Math.ceil(day / 7);
        weeks[w] = (weeks[w] || 0) + 1;
      });
      const lastDay = new Date(Number(year), Number(month), 0).getDate();
      const weekRows = [1, 2, 3, 4, 5].filter(w => (w - 1) * 7 + 1 <= lastDay).map(w => {
        const from = (w - 1) * 7 + 1; const to = Math.min(w * 7, lastDay);
        const n = weeks[w] || 0;
        return [`Week ${w} (${monthLabel(month)} ${from}–${to})`, n, `${cases.length ? Number(((n / cases.length) * 100).toFixed(1)) : 0}%`];
      });
      blocks.push({ id: 'weekly', title: 'Weekly Distribution of Diagnoses', kind: 'table', headers: ['Week', 'Cases', 'Percentage'], rows: weekRows });
    }
  }

  if (facilityPerformance?.length) {
    blocks.push({
      id: 'facility', title: 'Facility Performance', kind: 'table',
      headers: ['Facility', 'Cases', 'Success Rate'],
      rows: facilityPerformance.map(f => [f.facility, f.total_cases, f.evaluated > 0 ? `${((f.successful / f.evaluated) * 100).toFixed(1)}%` : 'N/A']),
    });
  }

  if (forecast?.available) {
    const fRows = [
      ['Forecasted Cases', forecast.forecastedCases],
      ['Forecast Period', forecast.period],
      ['Forecast Scope', isCitywide ? `${forecast.barangays} barangays` : `Barangay ${barangay}`],
    ];
    if (forecast.methods?.length) {
      fRows.push(['Method', forecast.methods.map(m => (m === 'arima' ? 'ARIMA' : String(m).replace(/_/g, ' '))).join(', ')]);
    }
    blocks.push({ id: 'forecast', title: 'Forecast', kind: 'kv', rows: fRows });
    const monthsInReport = type === 'quarterly' ? 3 : (type === 'annual' || type === 'barangay') ? 12 : 1;
    const perMonth = total / monthsInReport;
    if (forecast.forecastedCases != null && perMonth > 0) {
      const pctDiff = Math.round(((forecast.forecastedCases - perMonth) / perMonth) * 100);
      interpret('forecast', `${forecast.forecastedCases} case${forecast.forecastedCases === 1 ? ' is' : 's are'} projected for ${forecast.period}, ${Math.abs(pctDiff) < 5 ? 'about the same as' : `${Math.abs(pctDiff)}% ${pctDiff > 0 ? 'above' : 'below'}`} this report's monthly average of ${Number(perMonth.toFixed(1))}. Forecasts are estimates based on past cases.`);
    }
  }

  if (trend?.length) {
    blocks.push({ id: 'trend', title: 'TB Case Trend', kind: 'table', headers: ['Month', 'Cases'], rows: trend.map(r => [r.label, r.cases]) });
    interpret('trend', trendInsight(trend, { valueKey: 'cases', previous: older ? { label: olderLabel, value: older.totalCases } : null }));
  }

  if (isCitywide && barangayDistribution?.length) {
    const riskBy = Object.fromEntries((riskSummary || []).map(r => [r.barangay, r]));
    blocks.push({
      id: 'barangays', title: 'TB Cases, Incidence and Risk by Barangay', kind: 'table',
      headers: ['Barangay', 'Cases', 'Population', incidenceLabel || 'Incidence / 100k', 'Risk', 'Trend'],
      rows: barangayDistribution.map(r => [
        r.barangay, r.cases, r.population ? r.population.toLocaleString() : 'N/A',
        r.incidence != null ? r.incidence : 'N/A', riskBy[r.barangay]?.riskLevel || 'No Data', riskBy[r.barangay]?.trendDirection || 'N/A',
      ]),
      textColumns: [0, 4, 5],
    });
    interpret('barangays', rankingInsight(barangayDistribution.map(r => ({ name: r.barangay, Cases: r.cases })), {
      previous: older?.barangayDistribution?.length ? { label: olderLabel, items: older.barangayDistribution.map(r => ({ name: r.barangay, Cases: r.cases })) } : null,
    }));
  }

  if (isCitywide && riskSummary?.length) {
    const levels = ['Very High', 'High', 'Medium', 'Low', 'No Data'];
    const byLevel = {};
    riskSummary.forEach(r => { (byLevel[r.riskLevel] = byLevel[r.riskLevel] || []).push(r); });
    const levelRows = levels.filter(l => byLevel[l]).map(l => [
      l, byLevel[l].length, byLevel[l].reduce((s, r) => s + (r.cases || 0), 0),
      [...byLevel[l]].sort((a, b) => (b.cases || 0) - (a.cases || 0)).slice(0, 5).map(r => r.barangay).join(', ') + (byLevel[l].length > 5 ? ', …' : ''),
    ]);
    blocks.push({
      id: 'riskDist', title: 'Risk Classification Summary', kind: 'table',
      headers: ['Risk Level', 'Barangays', 'Cases in Period', 'Barangays (top by cases)'], rows: levelRows, textColumns: [0, 3],
    });
    interpret('riskDist', riskInsight(riskSummary.map(r => ({ name: r.barangay, risk_class: r.riskLevel }))));
  }

  if (isCitywide && barangayDistribution?.length) {
    const top = [...barangayDistribution].sort((a, b) => (b.cases - a.cases) || ((b.incidence ?? -1) - (a.incidence ?? -1))).slice(0, 5);
    const share = n => (total ? `${Number(((n / total) * 100).toFixed(1))}%` : '0%');
    blocks.push({
      id: 'topBarangays', title: 'Barangays with the Most Cases', kind: 'table',
      headers: ['Rank', 'Barangay', 'Cases', 'Share of City Total', incidenceLabel || 'Incidence / 100k'],
      rows: top.map((r, i) => [i + 1, r.barangay, r.cases, share(r.cases), r.incidence != null ? r.incidence : 'N/A']),
      textColumns: [0, 1],
    });
    const withCases = new Set(barangayDistribution.map(r => r.barangay));
    const none = barangays?.filter(b => !withCases.has(b)) || [];
    if (none.length) {
      blocks.push({ id: 'noCases', title: 'Barangays with No Recorded Cases', kind: 'text', items: [none.join(', ')] });
    }
  }

  if (alerts?.length) {
    blocks.push({
      id: 'alerts', title: 'Alerts Raised in the Period', kind: 'table',
      headers: ['Severity', 'Alert', 'Barangay', 'Status'],
      rows: alerts.map(a => [String(a.severity || '').toUpperCase(), a.title, a.barangay_name || 'Multiple / City-wide', a.status || '—']),
      textColumns: [0, 1, 2, 3],
    });
  }

  if (interventions?.length) {
    blocks.push({
      id: 'interventions', title: 'Interventions in the Period', kind: 'table',
      headers: ['Intervention', 'Type', 'Barangay', 'Priority', 'Status', 'Target Date'],
      rows: interventions.map(i => [i.title, String(i.intervention_type || '').replace(/_/g, ' '), i.barangay_name || '—', i.priority || '—',
        String(i.status || '').replace(/_/g, ' '), i.target_date ? fmtDate(i.target_date) : '—']),
      textColumns: [0, 1, 2, 3, 4, 5],
    });
  }

  // Case line list: only for a single-barangay report, where it stays a readable length.
  if (!isCitywide && cases?.length && cases.length <= 150) {
    blocks.push({
      id: 'lineList', title: 'Case Line List', kind: 'table',
      headers: ['Case ID', 'Diagnosed', 'Sex', 'Age', 'Site', 'Bacteriological', 'Outcome'],
      rows: cases.map(c => [
        c.source_case_id || c.case_no || 'No Case ID',
        c.date_of_diagnosis ? new Date(c.date_of_diagnosis).toLocaleDateString('en-US') : '—',
        c.sex || '—', c.age ?? '—', c.anatomical_site || '—', c.bacteriological_status || '—',
        c.outcome_status || c.case_status || '—',
      ]),
      textColumns: [0, 1, 2, 4, 5, 6],
    });
  }

  // Notes and definitions: what each figure is based on, and where the data is incomplete.
  const notes = [];
  if (summary.cohortYear) notes.push(`Treatment success rate uses the ${summary.cohortYear} treatment cohort (patients who started treatment the year before the report year); it is not computed from the cases listed above.`);
  if (summary.fatalityEvaluated) notes.push('Case fatality rate is deaths divided by evaluated terminal outcomes (cured, completed, failed, lost to follow-up, died).');
  if (outcomeReconciliation?.unapprovedTotal > 0) notes.push(`${outcomeReconciliation.unapprovedTotal} record(s) carry an outcome value outside the approved categories and are not shown in the outcome breakdown.`);
  if (barangayDistribution?.length || barangayProfile) {
    const annualised = !(type === 'annual' || type === 'barangay');
    notes.push(`Incidence is cases per 100,000 ${year} population${annualised ? ', annualized from this period' : ''}.`);
  }
  if (riskAssessmentPeriod) notes.push(`Risk classification is the Random Forest model's latest assessment (${riskAssessmentPeriod}); the trend label is the long-term slope of monthly cases, not the latest few months.`);
  if (forecast?.available && forecast.outsideReportPeriod) notes.push('The forecast is the next stored forecast month after this report period, not a forecast of the period itself.');
  if (meta.latestCaseDate && meta.endDate && meta.latestCaseDate.slice(0, 7) < meta.endDate.slice(0, 7)) {
    notes.push(`Records in this report run through ${fmtDate(meta.latestCaseDate)}; later months of the period have no data yet, so totals are partial.`);
  }
  if (notes.length) blocks.push({ id: 'notes', title: 'Notes and Definitions', kind: 'list', items: notes });

  if (recommendations?.length) blocks.push({ id: 'recommendations', title: 'Recommendations', kind: 'list', items: recommendations });

  const gb = meta.generatedBy;
  const preparedBy = gb ? (gb.fullName && gb.fullName !== gb.username ? gb.fullName : gb.username) : '';
  return { type, title, headerTitle, subtitle, footerPeriod, blocks, preparedBy, reportRef: meta.reportRef || '' };
}

/* ─── Report Renderer ────────────────────────────────────────────────── */

function ReportBlock({ block }) {
  const { kind, headers, rows = [], items = [] } = block;
  let body;
  if (kind === 'text') {
    body = <div className="space-y-1">{items.map((line, i) => <p key={i} className="text-xs" style={{ color: '#1E293B' }}>{line}</p>)}</div>;
  } else if (kind === 'list') {
    body = <ol className="text-xs pl-4 space-y-1" style={{ color: '#1E293B', listStyleType: 'decimal' }}>{items.map((line, i) => <li key={i}>{line}</li>)}</ol>;
  } else if (rows.length === 0) {
    body = <p className="text-xs italic" style={{ color: '#9CA3AF' }}>{block.emptyText || 'No data available for this period.'}</p>;
  } else {
    const textCols = block.textColumns || [0];
    body = (
      <table className="w-full text-xs" style={{ borderCollapse: 'collapse', border: '1px solid #D1D5DB' }}>
        {kind === 'table' && (
          <thead>
            <tr style={{ background: '#0F2D52' }}>
              {headers.map((h, hi) => (
                <th key={hi} className={`py-2 px-3 font-bold uppercase ${textCols.includes(hi) ? 'text-left' : 'text-right'}`} style={{ color: '#ffffff', fontSize: 12, borderBottom: '1px solid #0F2D52' }}>{h}</th>
              ))}
            </tr>
          </thead>
        )}
        <tbody>
          {rows.map((row, ri) => (
            <tr key={ri} style={{ background: ri % 2 === 1 ? '#F8FAFC' : '#ffffff', borderBottom: '1px solid #E5E7EB' }}>
              {row.map((cell, ci) => (
                <td key={ci} className="py-2 px-3" style={{
                  color: ci === 0 ? '#1E293B' : '#374151', fontWeight: ci === 0 || kind === 'kv' ? 600 : 400,
                  textAlign: kind === 'kv' ? (ci === 0 ? 'left' : 'right') : (textCols.includes(ci) ? 'left' : 'right'),
                }}>{cell}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    );
  }
  return (
    <div style={{ breakInside: 'avoid' }}>
      <p className="text-xs font-bold uppercase mb-1" style={{ color: '#0F2D52', letterSpacing: '0.05em' }}>{block.title}</p>
      <div style={{ borderBottom: '1px solid #0F2D52', marginBottom: 6 }} />
      {body}
    </div>
  );
}

